plugins {
    alias(libs.plugins.taqvim.jvm.library)
}

dependencies {
    implementation(libs.networknt.json.schema.validator)
    implementation(libs.kotlinx.serialization.json)
    implementation(libs.kotlinpoet)
    // D-07: Persian dates of the Islamic Iran override table are checked with the A-02 calendar; the golden test
    // compares the table with :core:calendar's IranOfficialMonthStarts.
    implementation(projects.core.calendar)
}

val datasetDirectory = rootProject.layout.projectDirectory.dir("dataset")

// `./gradlew :tools:dataset:validateOverrides` — D-07 Islamic Iran override tables (dataset/**/*-overrides.json).
tasks.register<JavaExec>("validateOverrides") {
    group = "verification"
    description = "Validates dataset/**/*-overrides.json against dataset/islamic-iran-overrides.v1.json (D-07)."
    classpath = sourceSets["main"].runtimeClasspath
    mainClass.set("ir.taqvim.tools.dataset.OverridesCliKt")
    args(datasetDirectory.file("islamic-iran-overrides.v1.json").asFile.path, datasetDirectory.asFile.path)
}

// `./gradlew :tools:dataset:validate` — D-01 validator CLI over dataset/**/*.json, plus the D-07 override tables.
tasks.register<JavaExec>("validate") {
    group = "verification"
    description = "Validates dataset/**/*.json against dataset/events.v1.json and the cross-record rules (D-01)."
    classpath = sourceSets["main"].runtimeClasspath
    mainClass.set("ir.taqvim.tools.dataset.DatasetCliKt")
    args(datasetDirectory.file("events.v1.json").asFile.path, datasetDirectory.asFile.path)
    dependsOn("validateOverrides")
}

// Generated `:data:events` sources (D-08); committed, regenerated by `generateEvents`, checked for staleness by tests.
val generatedEventsDirectory =
    rootProject.layout.projectDirectory.dir("data/events/src/main/kotlin/ir/taqvim/data/events/generated")

tasks.register<JavaExec>("generateEvents") {
    group = "build"
    description = "Generates data/events Kotlin sources from dataset/**/*.json after validating them (D-08)."
    classpath = sourceSets["main"].runtimeClasspath
    mainClass.set("ir.taqvim.tools.dataset.GenerateEventsCliKt")
    args(
        datasetDirectory.file("events.v1.json").asFile.path,
        datasetDirectory.asFile.path,
        generatedEventsDirectory.asFile.path,
    )
}

// Official daily rows extracted from the Calendar Center's calendars (golden fixtures of :core:calendar, T-102).
val officialDaysDirectory = rootProject.layout.projectDirectory.dir("core/calendar/src/test/resources/golden/persian")

tasks.withType<Test>().configureEach {
    systemProperty("taqvim.dataset.schema", datasetDirectory.file("events.v1.json").asFile.path)
    systemProperty(
        "taqvim.overrides.schema",
        datasetDirectory.file("islamic-iran-overrides.v1.json").asFile.path,
    )
    systemProperty("taqvim.dataset.directory", datasetDirectory.asFile.path)
    systemProperty("taqvim.official.days.directory", officialDaysDirectory.asFile.path)
    inputs.dir(datasetDirectory).withPathSensitivity(PathSensitivity.RELATIVE)
    inputs.dir(officialDaysDirectory).withPathSensitivity(PathSensitivity.RELATIVE)
    systemProperty("taqvim.generated.events.directory", generatedEventsDirectory.asFile.path)
    inputs.files(generatedEventsDirectory).withPathSensitivity(PathSensitivity.RELATIVE)
}
