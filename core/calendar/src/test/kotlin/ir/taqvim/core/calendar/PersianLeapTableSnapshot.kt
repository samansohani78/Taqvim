package ir.taqvim.core.calendar

/**
 * The Solar Hijri leap years of SH −3000‥3000 exactly as ADR-0008 shipped them in the app (generated from the A-02
 * rule with cosinekitty/astronomy 2.1.19 equinoxes). Since ADR-0026 the app computes year starts at run time; this
 * frozen snapshot catches any change of the computed years, for example after a library upgrade.
 */
internal object PersianLeapTableSnapshot {
    /** First year of the snapshot. */
    const val FIRST_YEAR: Int = -3000

    /** Last year of the snapshot. */
    const val LAST_YEAR: Int = 3000

    /** JDN of 1 Farvardin [FIRST_YEAR] (22 March 2379 BC, proleptic Gregorian). */
    const val FIRST_YEAR_START_JDN: Long = 852_229L

    private const val BITS_PER_BYTE = 8
    private const val HEX_DIGITS_PER_BYTE = 2
    private const val HEX_RADIX = 16

    /** Little-endian bit set in hex: bit `i` of byte `i / 8` is set when year `FIRST_YEAR + i` is a leap year. */
    private const val LEAP_BITS: String =
        "081111111122222242444444848888880811111111222222224444444488888808111111112222222244444444888888" +
            "081111111122222222444444848888880811111111222222224444444488888808111111112222222244444444888888" +
            "881011111121222222444444448888888810111111222222224444444488888888101111112122222244444444888888" +
            "881011111121222222444444448888888810111111212222224444444488888888101111112122222242444444848888" +
            "880811111121222222424444448488888808111111212222224244444484888888081111112122222222444444448888" +
            "880811111111222222224444444488888808111111112222222244444444888888081111111121222222424444448888" +
            "888810111111212222224244444488888888101111112122222242444444848888880811111111222222424444448488" +
            "888808111111112222222244444444888888881011111121222222444444448888888810111111212222224244444484" +
            "888888081111111122222222444444848888880811111111222222224444444488888888101111112122222244444444" +
            "888888880811111111222222424444448488888808111111112222222244444444888888881011111121222222444444" +
            "448888888810111111212222224244444484888888081111111122222222444444448888888810111111212222224444" +
            "444488888888101111112122222242444444848888880811111111222222224444444488888888101111112122222242" +
            "444444888888881011111111222222424444448488888808111111112222222244444444888888881011111121222222" +
            "424444448488888810111111112222222244444444888888081111111122222222444444448888888810111111212222" +
            "224244444484888888081111111122222222444444448888888810111111212222224244444484888888081111112122" +
            "22222244444444888888881011111122222222444444448888888810111101"

    /** Whether [year] (which must lie in the snapshot) has 366 days. */
    fun isLeap(year: Int): Boolean {
        require(year in FIRST_YEAR..LAST_YEAR) { "year $year is outside the Persian leap table snapshot" }
        val index = year - FIRST_YEAR
        val offset = index / BITS_PER_BYTE * HEX_DIGITS_PER_BYTE
        val byte = LEAP_BITS.substring(offset, offset + HEX_DIGITS_PER_BYTE).toInt(HEX_RADIX)
        return (byte shr (index % BITS_PER_BYTE)) and 1 == 1
    }
}
